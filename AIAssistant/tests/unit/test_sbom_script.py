"""Tests for the SBOM generator (ADR 0023).

The script lives outside ``src/``, so it is loaded by path. The cases pin what
matters for supply chain: dependency versions *and their SHA-256 digests* come
from the lock (never the floating requirements), and every model artifact
carries the revision + SHA-256 the loader enforces.
"""
from __future__ import annotations

import importlib.util
import io
import json
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path

_SCRIPT = Path(__file__).resolve().parents[2] / "scripts" / "generate_sbom.py"
_ROOT = Path(__file__).resolve().parents[2]


def _load_script():
    spec = importlib.util.spec_from_file_location("generate_sbom", _SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class ParseLockTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.script = _load_script()

    def test_pins_hashes_and_markers_are_read_and_noise_is_stripped(self) -> None:
        digest_a, digest_b = "a" * 64, "b" * 64
        with tempfile.TemporaryDirectory() as directory:
            lock = Path(directory) / "requirements.lock"
            lock.write_text(
                "# autogenerated\n"
                "fastapi==0.136.1 \\\n"
                f"    --hash=sha256:{digest_a} \\\n"
                f"    --hash=sha256:{digest_b}\n"
                "    #   via llama-index\n"
                "faiss-cpu==1.15.1 ; sys_platform == 'win32'\n"
                "not-a-pin>=1.0\n",
                encoding="utf-8",
            )
            components = self.script.parse_lock(lock)
        self.assertEqual([c["name"] for c in components], ["fastapi", "faiss-cpu"])
        self.assertEqual(components[0]["purl"], "pkg:pypi/fastapi@0.136.1")
        self.assertEqual(components[1]["version"], "1.15.1")
        self.assertEqual(
            components[0]["hashes"],
            [{"alg": "SHA-256", "content": digest_a},
             {"alg": "SHA-256", "content": digest_b}],
        )
        # A pin without --hash lines must not grow an empty "hashes" key; the
        # lock-level test below is what fails until the file is regenerated.
        self.assertNotIn("hashes", components[1])

    def test_the_tracked_lock_is_pinned_and_non_empty(self) -> None:
        components = self.script.parse_lock(_ROOT / "requirements.lock")
        self.assertGreater(len(components), 10)
        self.assertTrue(all("==" not in c["version"] for c in components))


class LockPinningTests(unittest.TestCase):
    """Both tracked locks must pin every distribution by version *and* hash.

    CI installs ``requirements-test.lock`` with ``--require-hashes``; a lock
    that regressed to version-only would either fail that install or let a
    republished artifact through, so the suite keeps both files in the shape
    the install needs (ADR 0023).
    """

    @classmethod
    def setUpClass(cls) -> None:
        cls.script = _load_script()

    def test_both_tracked_locks_pin_every_distribution_with_sha256(self) -> None:
        for name, floor in (("requirements.lock", 160), ("requirements-test.lock", 75)):
            with self.subTest(lock=name):
                components = self.script.parse_lock(_ROOT / name)
                self.assertGreater(len(components), floor)
                for component in components:
                    with self.subTest(package=component["name"]):
                        entries = component.get("hashes", [])
                        self.assertTrue(entries, "distribution without a pinned hash")
                        for entry in entries:
                            self.assertEqual(entry["alg"], "SHA-256")
                            self.assertRegex(entry["content"], r"^[0-9a-f]{64}$")


class ModelComponentsTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.script = _load_script()

    def test_every_tracked_model_carries_revision_and_sha256(self) -> None:
        components = self.script.model_components(_ROOT / "config")
        by_name = {c["name"]: c for c in components}
        # The vision projector is an artifact of its own and must be listed.
        self.assertIn("mmproj-Qwen_Qwen2.5-VL-7B-Instruct-f16.gguf", by_name)
        for component in components:
            with self.subTest(model=component["name"]):
                properties = {p["name"]: p["value"] for p in component["properties"]}
                self.assertEqual(len(properties["aiassistant:model:revision"]), 40)
                self.assertEqual(len(properties["aiassistant:model:sha256"]), 64)
                self.assertEqual(component["version"], properties["aiassistant:model:sha256"])


class MainFlowTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.script = _load_script()

    def test_main_writes_a_document_containing_both_halves(self) -> None:
        out = io.StringIO()
        with redirect_stdout(out):
            code = self.script.main([])
        self.assertEqual(code, 0)
        document = json.loads(out.getvalue())
        self.assertEqual(document["bomFormat"], "CycloneDX")
        kinds = {c["type"] for c in document["components"]}
        self.assertEqual(kinds, {"library", "machine-learning-model"})

    def test_output_flag_writes_a_file(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            target = Path(directory) / "sbom.json"
            code = self.script.main(["--output", str(target)])
            self.assertEqual(code, 0)
            self.assertTrue(target.exists())
            self.assertEqual(json.loads(target.read_text(encoding="utf-8"))["specVersion"], "1.5")

    def test_a_missing_lock_file_fails_closed(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            missing = Path(directory) / "absent.lock"
            code = self.script.main(["--lock", str(missing)])
        self.assertEqual(code, 2)


if __name__ == "__main__":
    unittest.main()
